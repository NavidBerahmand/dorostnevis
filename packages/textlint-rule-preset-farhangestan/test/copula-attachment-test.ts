import TextLintTester from "textlint-tester";
import rule from "../src/rules/copula-attachment";
import { inv, z } from "./helpers";

new TextLintTester().run("copula-attachment", rule, {
    valid: [
        "ای کاش رفته بود", // «ای کاش»: not «رفته‌ای»

        "این کار انجام شده است.",
        z("خسته‹اند"),
        z("خسته‹ام، خسته‹ای، خسته است، خسته‹ایم، خسته‹اید، خسته‹اند"), // p. 42
        z("ایرانی‹ام، ایرانی است، ایرانی‹اند"),
        "گفتی ای دوست که می‌آیی",   // vocative «ای»
        "کوه ام",                      // pronounced «ه»: left alone
        "گفت ای خدا",                 // vocative after a consonant
        "خسته است و دانا است",
        "اجزائی و سمائی و سوئی", // final hamza + ی: «ئ» (p. 51)
        "دانشجو ام"                    // «و» endings vary (دانشجویم، رهروم، رادیوام): left alone
    ],
    invalid: [
        // silent «ه» + « ای/ایی/ئی» or «‌ایی»: «ه‌ای» (1.4.0)
        inv("علی خامنه ایی مشاهده کردم", z("علی خامنه‹ای مشاهده کردم")),
        inv("خامنه ایی ۳۶", z("خامنه‹ای ۳۶")),
        inv("خامنه ای گفت", z("خامنه‹ای گفت")),
        inv(z("خامنه‹ایی گفت"), z("خامنه‹ای گفت")),
        inv("خامنه ئی گفت", z("خامنه‹ای گفت")),
        inv("خانه ای خرید", z("خانه‹ای خرید")),

        inv(z("این کار انجام شده‹است."), "این کار انجام شده است."),
        inv(z("او رفته‹است"), "او رفته است"),
        inv("من خسته ام.", z("من خسته‹ام.")),
        inv("خانه ای خریدند.", z("خانه‹ای خریدند.")),
        inv("ایرانی اند", z("ایرانی‹اند")),
        inv("خانه اش بزرگ است.", z("خانه‹اش بزرگ است.")),
        inv("خانه شان بزرگ است.", z("خانه‹شان بزرگ است.")), // p. 44
        inv("کشتی ای آمد.", z("کشتی‹ای آمد.")), // p. 45
        inv("کتاب اش را برد.", "کتابش را برد."),
        inv("برادر ام آمد.", "برادرم آمد."),
        inv("ما پاک اند.", z("ما پاک‹اند.")), // p. 42
        inv("من خشنود ام.", "من خشنودم."),
        inv("پا یم درد می‌کند.", "پایم درد می‌کند."),
        inv("عمو یش آمد.", "عمویش آمد."),
        inv("پا ام درد می‌کند.", "پایم درد می‌کند."),
        inv("خانه یی خرید.", z("خانه‹ای خرید.")),
        inv(z("کشتی‹یی آمد."), z("کشتی‹ای آمد.")),
        { text: "دانشجوئی آمد.", output: "دانشجوئی آمد.", errors: [{}] }, // both mediators allowed (fn 18): suggestion
        { text: "جائی رفت.", output: "جائی رفت.", errors: [{}] }, // both mediators allowed (fn 18): suggestion
        { text: "رادیوئی خرید.", output: "رادیوئی خرید.", errors: [{}] }, // both mediators allowed (fn 18): suggestion
        // «شان» after a consonant may be «شأن»: suggestion only
        { text: "کتاب شان", output: "کتاب شان", errors: [{}] }
    ]
});
