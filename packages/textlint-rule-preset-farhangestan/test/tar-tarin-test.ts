import TextLintTester from "textlint-tester";
import rule from "../src/rules/tar-tarin";
import { inv, z } from "./helpers";

new TextLintTester().run("tar-tarin", rule, {
    valid: [
        "فیلتر شد و فیلترها را برداشت.",
        "جدیدترین خبر",
        z("بزرگ‹تر، بزرگ‹ترین، وسیع‹تر"),
        "بهتر، کهتر، مهتر، بیشتر، کمتر، بیشترین",
        "لباس تر را پهن کرد.",          // «تر» = wet
        "دختر و دفتر و کبوتر",
        "پسوندهای تر و ترین",           // the suffixes named as words
        "دکتر و بستر و مستتر",          // «Xتر» is a word of its own
        "دورتر و زیباتر"                // non-joining letter: nothing to change
    ],
    invalid: [
        inv("بزرگ ترین شهر", z("بزرگ‹ترین شهر")),
        inv("این خانه بزرگ تر از آن است.", z("این خانه بزرگ‹تر از آن است.")),
        inv("دور ترین نقطه", "دورترین نقطه"),       // after a non-joining letter: no ZWNJ
        inv(z("بیش‹تر مردم"), "بیشتر مردم"),
        inv("کم ترین", "کمترین"),
        inv("خانهٔ بزرگتر", z("خانهٔ بزرگ‹تر")),
        inv("سریعترین راه", z("سریع‹ترین راه")),
        inv("یک راه سادهتر", z("یک راه ساده‹تر")),
        inv("خوبتری پیدا کن", z("خوب‹تری پیدا کن")),
        inv("بزرگترها می‌گفتند", z("بزرگ‹ترها می‌گفتند")),
        inv(z("بزرگتر‹اند"), z("بزرگ‹تر‹اند")),
        inv("سنگین تر می‌شود", z("سنگین‹تر می‌شود")),
        inv("مسن تر شد", z("مسن‹تر شد")),
        inv("زبانی بزرگ تری بود", z("زبانی بزرگ‹تری بود"))
    ]
});
