import TextLintTester from "textlint-tester";
import rule from "../src/rules/spaced-compounds";
import { inv, z } from "./helpers";

new TextLintTester().run("spaced-compounds", rule, {
    valid: [z("رئیس‹جمهور"), z("جمع‹آوری"), "رئیس دفتر", "جمع و آوری", "زبان فارسی زبان رسمی است.", "او به فارسی زبان باز کرد.",
        // the spaced form is a phrase: a preposition («در گذشته») or a verb («قرار داد»، «دست یابیم»)
        "در گذشته چنین بود", "قرار داد که برود", "به این مهم دست یابیم", "شناخته شده است",
        // a light verb next: «باز کرد», not «زبان‌باز»
        "زبان باز کرد", z("کارِ خانه")],
    invalid: [
        inv("رئیس جمهور آمد", z("رئیس‹جمهور آمد")),
        inv("رئیس جمهوری", z("رئیس‹جمهوری")),
        // the 2nd edition of دستور خط writes it joined, the farhang with a ZWNJ: the book wins
        {
            text: "بخش نامه",
            output: "بخشنامه",
            errors: [{ message: "این ترکیب یک کلمه است و پیوسته نوشته می‌شود: «بخشنامه» (دستور خط (ویراست جدید)؛ فرهنگ املایی، ص ۹۹، «بخش‌نامه» دارد)" }]
        },
        inv(z("جمع آوری‹ها"), z("جمع‹آوری‹ها")),
        inv("سازمان بین المللی", z("سازمان بین‹المللی")),
        inv("کشورهای انگلیسی زبان", z("کشورهای انگلیسی‹زبان")),
        inv("فارسی زبانان ازبکستان", z("فارسی‹زبانان ازبکستان")),
        inv("مردم عربی زبان", z("مردم عربی‹زبان")),
        inv("آیت الله بروجردی", z("آیت‹الله بروجردی")),
        inv("خط نصف النهار", z("خط نصف‹النهار")),
        inv(z("کشورهای غیر‹انگلیسی زبان"), z("کشورهای غیر‹انگلیسی‹زبان")),
        // 1.3.2: every compound of the farhang, not only those Wikipedia writes as one word
        {
            text: "دانش آموزان مدرسه",
            output: z("دانش‹آموزان مدرسه"),
            errors: [{ message: "این ترکیب یک کلمه است و با نیم‌فاصله نوشته می‌شود: «دانش‌آموز» (فرهنگ املایی، ص ۲۹۲)" }]
        },
        inv("دانش آموز", z("دانش‹آموز")),
        inv("باستان شناسان", z("باستان‹شناسان")),
        inv(z("کربن دی‹اکسید"), z("کربن‹دی‹اکسید")),
        inv("رسول الله", z("رسول‹الله")),
        // can also be two words («خانهٔ دار»، «شورایِ عالی»): reported, with no automatic fix
        {
            text: "خانه دار بود",
            output: "خانه دار بود",
            errors: [{ message: "اگر «خانه دار» یک واژه است، با نیم‌فاصله نوشته می‌شود: «خانه‌دار» (فرهنگ املایی، ص ۲۶۱)" }]
        },
        { text: "شورای عالی انقلاب", output: "شورای عالی انقلاب", errors: [{}] },
        // a suffix that makes the last part a word of its own («آموزش»): two words, maybe
        {
            text: "دانش آموزش",
            output: "دانش آموزش",
            errors: [{ message: "اگر «دانش آموزش» یک واژه است، با نیم‌فاصله نوشته می‌شود: «دانش‌آموزش» (فرهنگ املایی، ص ۲۹۲)" }]
        }
    ]
});
