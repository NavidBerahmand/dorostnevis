const squash = (s: string) => s.replace(/[ \u200c]/g, "");

interface Entry {
    right: string;
    source: string;
}
const ENTRIES = new Map<string, Entry>();
const alternatives: string[] = [];
for (const [pre, wrong, right, src] of ROWS) {
    const source =
        src[0] === "n"
            ? `غلط ننویسیم، ابوالحسن نجفی، ص ${toPersianDigits(src.slice(1))}`
            : `فرهنگ املایی خطّ فارسی، ص ${toPersianDigits(src.slice(1))}`;
    // «تاثیرگزار»: also without the hamza
    for (const p of new Set([pre, pre.replace(/أ/g, "ا")])) {
        ENTRIES.set(p + wrong, { right, source });
        const sep = p.length >= 3 ? `[ ${ZWNJ}]?` : `${ZWNJ}?`;
        alternatives.push(escapeRegExp(p) + sep + wrong);
    }
}
const SUFFIX = "(ی|ان|انی|ها|های)?";
const PATTERN = new RegExp(`${START}(${alternatives.sort((a, b) => b.length - a.length).join("|")})${SUFFIX}(?=${ZWNJ}|${END})`, "g");

/** The right form of a word this rule corrects («سپاسگذاران» → «سپاسگزاران»), or null. */
export function gozarCorrection(word: string): string | null {
    const w = squash(word);
    for (const suffix of ["", "ی", "ان", "انی", "ها", "های"]) {
        if (!w.endsWith(suffix)) continue;
        const e = ENTRIES.get(w.slice(0, w.length - suffix.length));
        if (e) return e.right + suffix;
    }
    return null;
}

export default createPatternRule(() => ({
    source: "غلط ننویسیم، ابوالحسن نجفی، ص ۳۱۹",
    checks: [
        {
            pattern: PATTERN,
            check: (m) => {
                const e = ENTRIES.get(squash(m[1]));
                if (!e) return null;
                const to = e.right + (m[2] ?? "");
                const meaning = e.right.includes("گزار")
                    ? "«گزاردن» یعنی «به‌جا آوردن، ادا کردن»"
                    : "«گذاشتن» یعنی «قرار دادن، وضع کردن»";
                return { message: `«${to}» درست است، نه «${m[0]}»: ${meaning}`, replacement: to, source: e.source };
            }
        }
    ]
}));
