import { TextlintKernel } from "@textlint/kernel";
import { DEFAULT_SETTINGS, lintText, isAuto, Msg } from "../src/lint-setup";
const kernel = new TextlintKernel();
async function auto(t: string) {
  for (let r = 0; r < 6; r++) {
    const ms = (await lintText(kernel, t, DEFAULT_SETTINGS, false, true)).filter((m: Msg) => m.fix && isAuto(m, t));
    if (!ms.length) break;
    const fx = ms.map((m) => m.fix!).sort((a, b) => a.range[0] - b.range[0]);
    const pick: any[] = []; let end = -1;
    for (const f of fx) { if (f.range[0] < end) continue; pick.push(f); end = f.range[1]; }
    for (const f of pick.reverse()) t = t.slice(0, f.range[0]) + f.text + t.slice(f.range[1]);
  }
  return t;
}
