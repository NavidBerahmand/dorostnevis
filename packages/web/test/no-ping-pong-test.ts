describe("no ping-pong: no rule takes back another's fix", function () {
    for (const [mode, texts] of [["formal", CASES], ["dialogue", [...CASES.slice(0, 26), ...DIALOGUE]]] as const) {
        it(`${mode}: ${texts.length} texts`, async () => {
            const problems: string[] = [];
            for (const t of texts) problems.push(...(await pingPong(t, { ...DEFAULT_SETTINGS, mode })));
            assert.deepStrictEqual(problems, [], "\n" + problems.join("\n"));
        });
    }

    it("the checker itself catches a ping-pong", async () => {
        // a book rule joins «۷۵ درصدی»; a convention without a fix objects to «۷۵درصدی»
        const book: Msg = { ruleId: "numbers", message: "پیوسته (دستور خط، ص ۶۵)", range: [0, 8], fix: { range: [0, 8], text: "۷۵درصدی" } };
        const lint = async (t: string): Promise<Msg[]> =>
            t === "۷۵درصدی" ? [{ ruleId: "punctuation", message: "فاصله (قراردادهای رایج (در دستور خط نیامده))", range: [0, 7] }] : [book];
        const found = await conflictsOf(lint, "۷۵ درصدی", book, [book]);
        assert.deepStrictEqual(found.map((c) => c.kind), ["flags"]);
        // and the convention, had it a fix, would be dropped on the page: it gives the old text back
        const conv: Msg = { ruleId: "punctuation", message: "فاصله (قراردادهای رایج (در دستور خط نیامده))", range: [0, 7], fix: { range: [0, 7], text: "۷۵ درصدی" } };
        const lint2 = async (t: string): Promise<Msg[]> => (t === "۷۵ درصدی" ? [book] : [conv]);
        const back = await conflictsOf(lint2, "۷۵درصدی", conv, [conv]);
        assert.ok(outranked(conv, back), JSON.stringify(back));
    });
});
