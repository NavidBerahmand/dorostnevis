import TextLintTester from "textlint-tester";
import rule from "../src/rules/redundant-verbs";
import { inv, z } from "./helpers";

const one = (text: string) => ({ text, errors: [{}] });
new TextLintTester().run("redundant-verbs", rule, {
    valid: [
        "باید آماده باشد", "او مسئول این کار است", "در مورد بررسی این طرح حرف زدیم",
        "پس از بررسی انجام شد", "کار انجام شد", "کارها را انجام داد", "او را مورد بررسی", "باشد که بیاید"
    ],
    invalid: [
        inv(z("او مسئول این کار می‹باشد"), "او مسئول این کار است"),
        inv("آن‌ها آماده میباشند", "آن‌ها آماده هستند"),
        inv(z("این درست نمی‹باشد"), "این درست نیست"),
        inv("طرح مورد بررسی قرار گرفت", "طرح بررسی شد"),
        inv(z("طرح مورد بررسی قرار می‹گیرد"), z("طرح بررسی می‹شود")),
        inv(z("لایحه مورد تصویب قرار گرفته‹است"), "لایحه تصویب شده است"),
        inv("گزارش را مورد ارزیابی قرار دادند", "گزارش را ارزیابی کردند"),
        inv("بررسی صورت گرفت", "بررسی شد"),
        inv("بررسی صورت پذیرفت", "بررسی شد"),
        inv("ثبت انجام شد", "ثبت شد"),
        inv("او بررسی انجام داد", "او بررسی کرد"),
        one("مورد توجه قرار گرفت"),
        one("مورد حمله قرار دادند")
    ]
});
