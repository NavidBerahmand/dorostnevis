/*
 * حرف اضافه (پیشنهاد، بدون اصلاح خودکار)
 *
 * - «جهت» به معنای «برای»: «جهت اطلاع» ← «برای اطلاع». «جهت» اسم هم هست
 *   («جهت باد»، «در این جهت»، «تغییر جهت»؛ حتی در آغاز جمله)، پس فقط پیش از
 *   اسم‌هایی که معمولاً هدف‌اند گزارش می‌شود («جهت اطلاع، جهت رفاه، جهت
 *   حفظ…»)، و نه پس از «در، از، به، این، آن، تغییر…» («در جهت حفظ» معنای
 *   دیگری دارد).
 * - «توسط» در جملهٔ مجهول: «نامه توسط مدیر نوشته شد» ← «مدیر نامه را نوشت».
 *   بازنویسی کار نویسنده است؛ فقط توضیح می‌آید.
 */
import { createPatternRule, START, END, SOURCE } from "../shared";

const PURPOSE = new Set([
    "اطلاع", "استفاده", "رفاه", "حفظ", "تأمین", "تامین", "بررسی", "کمک", "رفع", "جلوگیری", "تهیه", "انجام",
    "دریافت", "پرداخت", "ثبت", "شرکت", "ورود", "خرید", "ارسال", "اطلاعات", "مشاهده", "تسهیل", "ارتقای",
    "ارتقا", "بهبود", "پیشگیری", "آشنایی", "آموزش", "تکمیل", "درمان", "مطالعه", "تحقق", "اجرای", "ایجاد"
]);
/** «در جهت حفظ»، «از این جهت»، «تغییر جهت»: «جهت» the noun. */
const NOUN_BEFORE = new Set(["در", "از", "به", "این", "آن", "همین", "همان", "هر", "یک", "تغییر", "هم", "خلاف", "دو", "چند"]);
const PASSIVE = /(?:^|[\s‌])(?:شد|شدند|شده|می[‌ ]?شود|می[‌ ]?شوند|شود|شوند|نشد|گردید|گردیدند|می[‌ ]?گردد)(?=$|[\s.!?؟؛،,])/;

export default createPatternRule(() => ({
    source: SOURCE("حرف اضافه"),
    checks: [
        {
            pattern: new RegExp(`${START}جهت (\\S+)`, "g"),
            check: (m) => {
                const next = m[1].replace(/[.،؛:!?؟]+$/, "");
                const before = m.input.slice(Math.max(0, m.index - 20), m.index).match(/(\S+)\s+$/)?.[1] ?? "";
                if (!PURPOSE.has(next) || NOUN_BEFORE.has(before)) return null;
                return {
                    message: "اگر «جهت» به معنای «برای» است، «برای» ساده‌تر است",
                    replacement: "برای",
                    fix: false,
                    end: 3
                };
            }
        },
        {
            pattern: new RegExp(`${START}توسط${END}`, "g"),
            check: (m) => {
                // the rest of the sentence must have a passive verb
                const rest = m.input.slice(m.index).split(/[.!?؟؛\n]/)[0];
                if (!PASSIVE.test(rest)) return null;
                return {
                    message: "«توسط» در جملهٔ مجهول ترجمه‌وار است؛ بهتر است جمله معلوم شود: «نامه توسط مدیر نوشته شد» ← «مدیر نامه را نوشت»",
                    fix: false
                };
            }
        }
    ]
}));
