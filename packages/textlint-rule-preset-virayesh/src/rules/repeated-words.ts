/*
 * کلمهٔ تکراری پشت‌سرهم (پیشنهاد)
 *
 * «را را»، «و و»، «است است»: معمولاً از جاافتادن یا ویرایش نیمه‌کاره است.
 * فقط حرف‌های اضافه و ربط و چند فعل ربطی/کمکی بررسی می‌شوند، چون تکرار
 * بسیاری از کلمه‌ها در فارسی درست است: «کم کم»، «آرام آرام»، «تک تک».
 */
import { createPatternRule, START, END, SOURCE } from "../shared";

const WORDS = [
    "و", "را", "از", "به", "در", "با", "که", "این", "آن", "تا", "یا", "هم", "نیز", "برای", "اما", "ولی", "اگر",
    "است", "بود", "شد", "هست", "بودند", "شدند", "باید", "می‌شود", "کرد"
];

export default createPatternRule(() => ({
    source: SOURCE("تکرار"),
    checks: [
        {
            pattern: new RegExp(`${START}(${WORDS.join("|")})(\\s+\\1)${END}`, "g"),
            check: (m) => ({
                message: `«${m[1]}» دو بار پشت‌سرهم آمده است`,
                replacement: m[1]
            })
        }
    ]
}));
