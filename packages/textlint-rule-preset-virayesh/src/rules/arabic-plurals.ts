/*
 * جمع عربی (پیشنهاد)
 *
 * ۱. واژهٔ فارسی که به قیاس عربی جمع بسته شده: «اساتید، دراویش، فرامین،
 *    میادین» و «-ات» پس از واژهٔ فارسی: «گزارشات، آزمایشات، پیشنهادات».
 *    جمع فارسی‌اش («استادان، گزارش‌ها») توصیه می‌شود.
 * ۲. «-ین» در جمع صفت‌ها و اسم‌های عربی که در فارسی «-ان» می‌گیرند:
 *    «مسئولین، معلمین، متخصصین» ← «مسئولان، معلمان، متخصصان». این جمع در
 *    فارسی سابقه دارد؛ پیشنهاد فقط برای یکدستی و سادگی است.
 *
 * فهرست بسته است. ترکیب‌ها و نام‌های جاافتاده («والدین»، «طرفین»، «مسلمین»،
 * «مؤمنین»، «مهاجرین و انصار»، «سازمان بنادر»، «کارخانجات»، «دهات») در آن نیستند.
 */
import { createPatternRule, START, END, SOURCE, flex, squash } from "../shared";

const PERSIAN_WORD_ARABIC_PLURAL: Record<string, string> = {
    اساتید: "استادان", دراویش: "درویشان", فرامین: "فرمان‌ها", میادین: "میدان‌ها",
    گزارشات: "گزارش‌ها", آزمایشات: "آزمایش‌ها", پیشنهادات: "پیشنهادها", سفارشات: "سفارش‌ها",
    فرمایشات: "فرمایش‌ها", نگارشات: "نگارش‌ها", دستورات: "دستورها", باغات: "باغ‌ها", گرایشات: "گرایش‌ها",
    خواهشات: "خواهش‌ها", نمایشات: "نمایش‌ها", آزمونات: "آزمون‌ها"
};

const IN_PLURAL: Record<string, string> = {
    مسئولین: "مسئولان", مسؤولین: "مسئولان", معلمین: "معلمان", مهندسین: "مهندسان", متخصصین: "متخصصان",
    مأمورین: "مأموران", مامورین: "مأموران", محققین: "محققان", منتقدین: "منتقدان", مدیرین: "مدیران",
    مسافرین: "مسافران", متهمین: "متهمان", مخاطبین: "مخاطبان", مراجعین: "مراجعان", حاضرین: "حاضران",
    داوطلبین: "داوطلبان", مشترکین: "مشترکان", مفسرین: "مفسران", منتخبین: "منتخبان", مدرسین: "مدرسان",
    مترجمین: "مترجمان", مؤلفین: "مؤلفان", مولفین: "مؤلفان", مصنفین: "مصنفان", متقاضیین: "متقاضیان",
    ناظرین: "ناظران", شاهدین: "شاهدان", مجرمین: "مجرمان", مقصرین: "مقصران", مشاورین: "مشاوران",
    متخلفین: "متخلفان"
};

const ALL = new Map<string, [string, boolean]>();
for (const [k, v] of Object.entries(PERSIAN_WORD_ARABIC_PLURAL)) ALL.set(squash(k), [v, true]);
for (const [k, v] of Object.entries(IN_PLURAL)) ALL.set(squash(k), [v, false]);

export default createPatternRule(() => ({
    source: SOURCE("جمع عربی"),
    checks: [
        {
            pattern: new RegExp(`${START}(${[...Object.keys(PERSIAN_WORD_ARABIC_PLURAL), ...Object.keys(IN_PLURAL)].sort((a, b) => b.length - a.length).map(flex).join("|")})${END}`, "g"),
            check: (m) => {
                const hit = ALL.get(squash(m[1]));
                if (!hit) return null;
                const [to, persianWord] = hit;
                return {
                    message: persianWord
                        ? `«${m[1]}» جمعِ عربیِ واژه‌ای فارسی است؛ جمع فارسی‌اش توصیه می‌شود: «${to}»`
                        : `جمع با «-ان» در فارسی رایج‌تر است: «${to}»`,
                    replacement: to
                };
            }
        }
    ]
}));
