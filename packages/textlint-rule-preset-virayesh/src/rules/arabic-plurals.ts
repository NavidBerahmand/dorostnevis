/*
 * جمع عربی (پیشنهاد)
 *
 * ۱. واژهٔ فارسی که به قیاس عربی جمع بسته شده: «اساتید، دراویش، فرامین،
 *    میادین» و «-ات» پس از واژهٔ فارسی: «گزارشات، آزمایشات، پیشنهادات».
 *    جمع فارسی‌اش («استادان، گزارش‌ها») توصیه می‌شود.
 * ۲. «-ین» در جمع صفت‌ها و اسم‌های عربی که در فارسی «-ان» می‌گیرند:
 *    «مسئولین، معلمین، متخصصین» ← «مسئولان، معلمان، متخصصان». این جمع در
 *    فارسی سابقه دارد؛ پیشنهاد فقط برای یکدستی و سادگی است.
 *
 * ۳. جمع‌های نادرست از غلط ننویسیم (ابوالحسن نجفی): «اثرات» ← «آثار» یا «اثرها» (ص ۱۴)؛
 *    «خطرات، اقشار، احجام، اسهام، تراوشات، تلگرافات، شعبات، دواوین، دهاقین، بساتین، رنود»
 *    ← «خطرها، قشرها، حجم‌ها، سهام…»؛ «اشعه‌ها» ← «اشعه» (اشعه خود جمع «شعاع» است، ص ۲۷).
 *    پیش از کلمه‌ای که مضاف‌الیه یا صفت می‌نماید شکل اضافه پیشنهاد می‌شود: «اقشار مختلف»
 *    ← «قشرهای مختلف»؛ پیش از «و، را، از…»، فعل یا نشانه: «خطرها».
 *
 * فهرست بسته است. ترکیب‌ها و نام‌های جاافتاده («والدین»، «طرفین»، «مسلمین»،
 * «مؤمنین»، «مهاجرین و انصار»، «سازمان بنادر»، «کارخانجات»، «دهات») در آن نیستند.
 */
import { createPatternRule, START, END, SOURCE, flex, squash } from "../shared";

const PERSIAN_WORD_ARABIC_PLURAL: Record<string, string> = {
    اساتید: "استادان", دراویش: "درویشان", فرامین: "فرمان‌ها", میادین: "میدان‌ها",
    گزارشات: "گزارش‌ها", آزمایشات: "آزمایش‌ها", پیشنهادات: "پیشنهادها", سفارشات: "سفارش‌ها",
    فرمایشات: "فرمایش‌ها", نگارشات: "نگارش‌ها", دستورات: "دستورها", باغات: "باغ‌ها", گرایشات: "گرایش‌ها",
    خواهشات: "خواهش‌ها", نمایشات: "نمایش‌ها", آزمونات: "آزمون‌ها"
};

const IN_PLURAL: Record<string, string> = {
    مسئولین: "مسئولان", مسؤولین: "مسئولان", معلمین: "معلمان", مهندسین: "مهندسان", متخصصین: "متخصصان",
    مأمورین: "مأموران", مامورین: "مأموران", محققین: "محققان", منتقدین: "منتقدان", مدیرین: "مدیران",
    مسافرین: "مسافران", متهمین: "متهمان", مخاطبین: "مخاطبان", مراجعین: "مراجعان", حاضرین: "حاضران",
    داوطلبین: "داوطلبان", مشترکین: "مشترکان", مفسرین: "مفسران", منتخبین: "منتخبان", مدرسین: "مدرسان",
    مترجمین: "مترجمان", مؤلفین: "مؤلفان", مولفین: "مؤلفان", مصنفین: "مصنفان", متقاضیین: "متقاضیان",
    ناظرین: "ناظران", شاهدین: "شاهدان", مجرمین: "مجرمان", مقصرین: "مقصران", مشاورین: "مشاوران",
    متخلفین: "متخلفان"
};

const N = (page: string) => `غلط ننویسیم، ابوالحسن نجفی، ص ${page}`;
/** [plural form, page, note] */
const NAJAFI: Record<string, [string, string, string]> = {
    خطرات: ["خطرها", "۱۷۷", "«خطر» را نمی‌شود با «ـات» جمع بست"],
    اقشار: ["قشرها", "۳۳", "«اقشار» در عربی نیامده (جمع «قشر» در عربی «قشور» است)"],
    احجام: ["حجم‌ها", "۱۶", "«احجام» در عربی نیامده (جمع «حجم» در عربی «حجوم» است)"],
    اسهام: ["سهام", "۲۶", "«اسهام» در عربی نیامده؛ جمع «سهم» «سهام» است"],
    تراوشات: ["تراوش‌ها", "۱۰۴", "«تراوش» فارسی است و «ـات» عربی نمی‌گیرد"],
    تلگرافات: ["تلگراف‌ها", "۱۱۱", "«تلگراف» فرانسوی است و «ـات» عربی نمی‌گیرد"],
    شعبات: ["شعبه‌ها", "۲۴۳", "«شعبات» ساختهٔ فارسی‌زبانان است"],
    دواوین: ["دیوان‌ها", "۱۹۵", "«دیوان» فارسی است و در فارسی بهتر است با «ها» جمع بسته شود"],
    دهاقین: ["دهقانان", "۱۹۷", "«دهقان» معرّب «دهگان» فارسی است و در فارسی بهتر است «دهقانان» گفته شود"],
    بساتین: ["بوستان‌ها", "۷۰", "«بستان» فارسی است و در فارسی بهتر است با «ها» جمع بسته شود"],
    رنود: ["رندان", "۲۱۴", "«رند» فارسی است و جمع عربی نمی‌گیرد"]
};
/** Najafi says «بهتر است» for these: a preference, not an error. */
const PREFERENCE = new Set(["دواوین", "دهاقین", "بساتین"]);
/** After these the plural ends its phrase: «خطرها و…»، «قشرها را…». Otherwise the ezafe form: «قشرهای مختلف». */
const PHRASE_END_WORDS = "و|را|که|از|به|در|با|برای|تا|یا|هم|نیز|است|هستند|بود|بودند|شد|شدند|دارد|دارند|داشت|داشتند|باشد|باشند|شود|شوند";
const PHRASE_END = new RegExp(`^(?:\\s*(?:[.،؛:!؟?)»\\]\\-]|$)|\\s+(?:(?:${PHRASE_END_WORDS})${END}|ن?می[ ‌]))`);
const ezafeForm = (plural: string) => (plural.endsWith("ها") ? plural + "ی" : plural);

const ALL = new Map<string, [string, boolean]>();
for (const [k, v] of Object.entries(PERSIAN_WORD_ARABIC_PLURAL)) ALL.set(squash(k), [v, true]);
for (const [k, v] of Object.entries(IN_PLURAL)) ALL.set(squash(k), [v, false]);

export default createPatternRule(() => ({
    source: SOURCE("جمع عربی"),
    checks: [
        {
            pattern: new RegExp(`${START}(${[...Object.keys(PERSIAN_WORD_ARABIC_PLURAL), ...Object.keys(IN_PLURAL)].sort((a, b) => b.length - a.length).map(flex).join("|")})${END}`, "g"),
            check: (m) => {
                const hit = ALL.get(squash(m[1]));
                if (!hit) return null;
                const [to, persianWord] = hit;
                return {
                    message: persianWord
                        ? `«${m[1]}» جمعِ عربیِ واژه‌ای فارسی است؛ جمع فارسی‌اش توصیه می‌شود: «${to}»`
                        : `جمع با «-ان» در فارسی رایج‌تر است: «${to}»`,
                    replacement: to
                };
            }
        },
        {
            pattern: new RegExp(`${START}(${Object.keys(NAJAFI).join("|")})${END}`, "g"),
            check: (m) => {
                const [plural, page, note] = NAJAFI[m[1]];
                const to = PHRASE_END.test(m.input.slice(m.index + m[0].length)) ? plural : ezafeForm(plural);
                // «دواوین، دهاقین، بساتین»: «بهتر است» in the book, a preference; the rest are wrong
                return { message: `${note}: «${to}»`, replacement: to, source: N(page), certain: !PREFERENCE.has(m[1]) };
            }
        },
        {
            pattern: new RegExp(`${START}اثرات${END}`, "g"),
            check: (m) => {
                const to = PHRASE_END.test(m.input.slice(m.index + m[0].length)) ? "اثرها" : "اثرهای";
                return {
                    message: `«اثرات» جمع نادرست است (مصدر سه‌حرفی «ـات» نمی‌گیرد): «${to}»، یا بسته به معنا «آثار»`,
                    replacement: to,
                    source: N("۱۴"),
                    certain: true
                };
            }
        },
        {
            pattern: new RegExp(`${START}اشعه[ ‌]?ها(ی)?${END}`, "g"),
            check: (m) => ({
                message: `«اشعه» خود جمع «شعاع» است و «ها» نمی‌گیرد: «${m[1] ? "پرتوهای" : "پرتوها"}»، «اشعه» یا «شعاع‌ها»`,
                replacement: m[1] ? "پرتوهای" : "پرتوها",
                source: N("۲۷"),
                certain: true
            })
        }
    ]
}));
